function circlePiece(
  canvas: SpriteCanvas,
  width: number,
  height: number,
  metrics: Metrics,
  x: number,
  y: number,
  w: number,
  h: number,
  corner: Corner,
): void {
  // Radius in pixels of the arc we need to draw.
  const wdth = width * w;
  const hght = height * h;

  // Position in pixels (rather than cells) for x/y
  const xp = width * x;
  const yp = height * y;

  // Ghostty sets the clip to the cell box (clip_* = padding_*) here so the
  // stroke doesn't bleed outside the cell; our padding is 0, so that's a
  // no-op (coverage() already clips to the cell-sized surface).

  // Coefficient for approximating a circular arc.
  const c = (Math.SQRT2 - 1.0) * 4.0 / 3.0;
  const cw = c * wdth;
  const ch = c * hght;

  const thick = metrics.boxThickness;
  const ht = thick * 0.5;

  const path = canvas.path();

  switch (corner) {
  case 'tl':
    path.moveTo(wdth - xp, ht - yp);
    path.curveTo(
      wdth - cw - xp,
      ht - yp,
      ht - xp,
      hght - ch - yp,
      ht - xp,
      hght - yp,
    );
    break;
  case 'tr':
    path.moveTo(wdth - xp, ht - yp);
    path.curveTo(
      wdth + cw - xp,
      ht - yp,
      wdth * 2 - ht - xp,
      hght - ch - yp,
      wdth * 2 - ht - xp,
      hght - yp,
    );
    break;
  case 'bl':
    path.moveTo(ht - xp, hght - yp);
    path.curveTo(
      ht - xp,
      hght + ch - yp,
      wdth - cw - xp,
      hght * 2 - ht - yp,
      wdth - xp,
      hght * 2 - ht - yp,
    );
    break;
  case 'br':
    path.moveTo(wdth * 2 - ht - xp, hght - yp);
    path.curveTo(
      wdth * 2 - ht - xp,
      hght + ch - yp,
      wdth + cw - xp,
      hght * 2 - ht - yp,
      wdth - xp,
      hght * 2 - ht - yp,
    );
    break;
  }

  canvas.strokePath(path, {
    cap: 'butt',
    width: metrics.boxThickness,
  }, SHADE_ON);
}
