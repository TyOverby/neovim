export const draw1CC1B_1CC1E: DrawFn = (cp, canvas, width, height, metrics) => {
  const w = width;
  const h = height;
  const t = metrics.boxThickness;
  switch (cp) {
  // 𜰛 BOX DRAWINGS LIGHT HORIZONTAL AND UPPER RIGHT
  case 0x1CC1B:
    linesChar(metrics, canvas, { left: 'light', right: 'light' });
    canvas.box(w - t, 0, w, idiv(h, 2), SHADE_ON);
    break;
  // 𜰜 BOX DRAWINGS LIGHT HORIZONTAL AND LOWER RIGHT
  case 0x1CC1C:
    linesChar(metrics, canvas, { left: 'light', right: 'light' });
    canvas.box(w - t, idiv(h, 2), w, h, SHADE_ON);
    break;
  // 𜰝 BOX DRAWINGS LIGHT TOP AND UPPER LEFT
  case 0x1CC1D:
    canvas.box(0, 0, w, t, SHADE_ON);
    canvas.box(0, 0, t, idiv(h, 2), SHADE_ON);
    break;
  // 𜰞 BOX DRAWINGS LIGHT BOTTOM AND LOWER LEFT
  case 0x1CC1E:
    canvas.box(0, h - t, w, h, SHADE_ON);
    canvas.box(0, idiv(h, 2), t, h, SHADE_ON);
    break;
  }
};

