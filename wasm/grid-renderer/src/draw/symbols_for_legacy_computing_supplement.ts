// Octants
export const draw1CD00_1CDE5: DrawFn = (cp, canvas, _width, _height, metrics) => {
  const oct = octants[cp - octant_min];
  if (oct & 0x01) fill(metrics, canvas, 0, half, 0, one_quarter);
  if (oct & 0x02) fill(metrics, canvas, half, 1, 0, one_quarter);
  if (oct & 0x04) fill(metrics, canvas, 0, half, one_quarter, half);
  if (oct & 0x08) fill(metrics, canvas, half, 1, one_quarter, half);
  if (oct & 0x10) fill(metrics, canvas, 0, half, half, three_quarters);
  if (oct & 0x20) fill(metrics, canvas, half, 1, half, three_quarters);
  if (oct & 0x40) fill(metrics, canvas, 0, half, three_quarters, 1);
  if (oct & 0x80) fill(metrics, canvas, half, 1, three_quarters, 1);
};

// Separated Block Quadrants
// 𜰡 𜰢 𜰣 𜰤 𜰥 𜰦 𜰧 𜰨 𜰩 𜰪 𜰫 𜰬 𜰭 𜰮 𜰯
export const draw1CC21_1CC2F: DrawFn = (cp, canvas, width, height, _metrics) => {
  // Bits laid out to match the codepoint order (ghostty bit-casts the
  // offset into a packed struct { tl, tr, bl, br }).
  const bits = (cp - 0x1CC20) & 0xf;
  const tl = (bits & 0x1) !== 0;
  const tr = (bits & 0x2) !== 0;
  const bl = (bits & 0x4) !== 0;
  const br = (bits & 0x8) !== 0;

  const gap = Math.max(1, idiv(width, 12));

  const mid_gap_x = gap * 2 + (width % 2);
  const mid_gap_y = gap * 2 + (height % 2);

  const w = idiv(width - gap * 2 - mid_gap_x, 2);
  const h = idiv(height - gap * 2 - mid_gap_y, 2);

  if (tl) canvas.box(
    gap,
    gap,
    gap + w,
    gap + h,
    SHADE_ON,
  );
  if (tr) canvas.box(
    gap + w + mid_gap_x,
    gap,
    gap + w + mid_gap_x + w,
    gap + h,
    SHADE_ON,
  );
  if (bl) canvas.box(
    gap,
    gap + h + mid_gap_y,
    gap + w,
    gap + h + mid_gap_y + h,
    SHADE_ON,
  );
  if (br) canvas.box(
    gap + w + mid_gap_x,
    gap + h + mid_gap_y,
    gap + w + mid_gap_x + w,
    gap + h + mid_gap_y + h,
    SHADE_ON,
  );
};

